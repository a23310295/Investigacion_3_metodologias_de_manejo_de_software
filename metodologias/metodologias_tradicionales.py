#1. Metodologías Tradicionales (Predictivas)
#Se basan en una planificación lineal y rigurosa. Todo se define al principio y no se esperan cambios durante el proceso.

#Waterfall (Cascada): Es el modelo clásico. El proyecto fluye hacia abajo a través de fases fijas: Requisitos → Diseño → Implementación → Verificación → Mantenimiento. No puedes pasar a la siguiente fase sin terminar la anterior.

#Modelo en V: Una variante de la cascada que pone el mismo peso en la ejecución que en las pruebas. Cada etapa de desarrollo tiene una etapa de validación correspondiente.
